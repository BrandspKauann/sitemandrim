import assert from 'node:assert/strict';
import { dayKey, trackStudy, selectedStats } from '../app/components/usageStats.ts';
const start = new Date(2026, 9, 1, 23, 59, 50).getTime();
const record = { sessionId: 'test', dailyVisibleMs: {}, studyDays: {} };
trackStudy(record, '/hsk1', start, start + 20000);
assert.equal(record.studyDays['2026-10-01'].visibleMs, 10000);
assert.equal(record.studyDays['2026-10-02'].pages['/hsk1'], 10000);
trackStudy(record, '/revisao', start + 20000, start + 25000);
record.dailyVisibleMs = { '2026-10-01': 10000, '2026-10-02': 15000 };
const oneDay = selectedStats([record], '2026-10-02', '2026-10-02');
assert.equal(oneDay.total, 15000);
assert.equal(oneDay.sessions.length, 1);
assert.deepEqual(oneDay.pages, [['/hsk1', 10000], ['/revisao', 5000]]);
assert.equal(oneDay.missingDetail, 0);
const legacy = { sessionId: 'old', dailyVisibleMs: { '2026-10-02': 45000 } };
const mixed = selectedStats([record, legacy], '2026-10-01', '2026-10-02');
assert.equal(mixed.total, 70000);
assert.equal(mixed.missingDetail, 45000);
assert.equal(selectedStats([record], '2027-01-01','2027-01-02').total, 0);
assert.equal(dayKey(start), '2026-10-01');
console.log('Study statistics: midnight split, areas, date filters and legacy totals passed.');
